# Converts a 400x300 PNG into Picture.h: one byte per pixel, 0bRRGGBB with
# 2 bits per colour, as the MCE Blaster DAC expects.
#
# $ python3 png2header.py Comic.png ../Picture.h
import sys
from PIL import Image

src, dst = sys.argv[1], sys.argv[2]
im = Image.open(src).convert('RGB')
assert im.size == (400, 300), im.size
px = im.load()
with open(dst, 'w') as f:
    f.write('// Generated by tools/png2header.py from Comic.png, do not edit.\n')
    f.write('#pragma once\n#include <cstdint>\n\n')
    f.write('static constexpr uint32_t PictureWidth = 400;\n')
    f.write('static constexpr uint32_t PictureHeight = 300;\n')
    f.write('static const uint8_t Picture[PictureHeight][PictureWidth] = {\n')
    for y in range(300):
        row = []
        for x in range(400):
            r, g, b = (round(c / 85) for c in px[x, y])
            row.append(r << 4 | g << 2 | b)
        f.write('{' + ','.join(str(v) for v in row) + '},\n')
    f.write('};\n')
