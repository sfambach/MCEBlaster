# Converts any picture (PNG, JPG, ...) into Picture.h: cropped to 4:3 around
# the centre, scaled to 400x300 and reduced to the 64 colours of the MCE
# Blaster DAC, one byte per pixel as 0bRRGGBB.
#
# $ python3 png2header.py MyPicture.jpg ../Picture.h [--dither]
#
# Also writes ../Picture_preview.png (800x600), which shows what the
# monitor will show.
import argparse
import os
from PIL import Image, ImageOps

W, H = 400, 300

ap = argparse.ArgumentParser()
ap.add_argument('src')
ap.add_argument('dst')
ap.add_argument('--dither', action='store_true',
                help='Floyd-Steinberg dithering, better for photos')
args = ap.parse_args()

im = ImageOps.exif_transpose(Image.open(args.src)).convert('RGB')
im = ImageOps.fit(im, (W, H), Image.LANCZOS)

lev = [0, 85, 170, 255]
pal = Image.new('P', (1, 1))
pal.putpalette([c for r in lev for g in lev for b in lev for c in (r, g, b)])
dither = Image.Dither.FLOYDSTEINBERG if args.dither else Image.Dither.NONE
im = im.quantize(palette=pal, dither=dither).convert('RGB')

px = im.load()
with open(args.dst, 'w') as f:
    f.write('// Generated by tools/png2header.py from %s, do not edit.\n'
            % os.path.basename(args.src))
    f.write('#pragma once\n#include <cstdint>\n\n')
    f.write('static constexpr uint32_t PictureWidth = %d;\n' % W)
    f.write('static constexpr uint32_t PictureHeight = %d;\n' % H)
    f.write('static const uint8_t Picture[PictureHeight][PictureWidth] = {\n')
    for y in range(H):
        row = []
        for x in range(W):
            r, g, b = (round(c / 85) for c in px[x, y])
            row.append(r << 4 | g << 2 | b)
        f.write('{' + ','.join(str(v) for v in row) + '},\n')
    f.write('};\n')

preview = os.path.join(os.path.dirname(os.path.abspath(args.dst)),
                       'Picture_preview.png')
im.resize((W * 2, H * 2), Image.NEAREST).save(preview)
print('Wrote', args.dst, 'and', preview)
